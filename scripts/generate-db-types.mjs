/**
 * Regenerates `src/types/database.ts` from a live Supabase project.
 *
 *   node scripts/generate-db-types.mjs --project-id <ref>      hosted project
 *   node scripts/generate-db-types.mjs --local                local `supabase start` stack
 *
 * Either pass `--project-id` / SUPABASE_PROJECT_ID, or `--local` after running
 * `npx supabase start`. For a hosted project, export SUPABASE_ACCESS_TOKEN
 * (personal access token) if the CLI cannot find a cached login.
 *
 * The schema lives in `supabase/migrations/`, so the migrations are the source
 * of truth — this script only keeps the TypeScript in step with them.
 */
import { spawn } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(ROOT, 'src', 'types', 'database.ts');

const args = process.argv.slice(2);
const useLocal = args.includes('--local');
const projectId =
  valueOf('--project-id') ?? process.env.SUPABASE_PROJECT_ID ?? null;

if (!useLocal && !projectId) {
  console.error(
    'Specify a project:\n' +
      '  node scripts/generate-db-types.mjs --project-id <ref>\n' +
      '  node scripts/generate-db-types.mjs --local'
  );
  process.exit(1);
}

function valueOf(flag) {
  const index = args.indexOf(flag);
  return index === -1 ? null : (args[index + 1] ?? null);
}

/** Preserves the hand-written helper types at the bottom of the current file. */
async function tailOfExistingFile() {
  try {
    const current = await readFile(OUT_FILE, 'utf8');
    const marker = 'export type TableRow<';
    const index = current.indexOf(marker);
    return index === -1 ? '' : current.slice(index);
  } catch {
    return '';
  }
}

const cli = ['--yes', 'supabase@latest', 'gen', 'types', 'typescript', '--schema', 'public'];
if (useLocal) cli.push('--local');
else cli.push('--project-id', projectId);

const generated = await run('npx', cli);
const tail = await tailOfExistingFile();

const header = [
  '/**',
  ' * Generated by `npm run db:types`. Do not edit by hand.',
  ' *',
  ' * Source of truth: `supabase/migrations/`.',
  ' */',
  '',
].join('\n');

await writeFile(OUT_FILE, header + generated.trimEnd() + '\n\n' + tail, 'utf8');
console.log(`Wrote ${OUT_FILE}`);

function run(command, commandArgs) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, commandArgs, { cwd: ROOT, stdio: ['ignore', 'pipe', 'inherit'] });
    let stdout = '';
    child.stdout.on('data', (chunk) => {
      stdout += chunk;
    });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) resolve(stdout);
      else reject(new Error(`${command} exited with code ${code}`));
    });
  });
}
